"""Shared data shapes (Action, Risk, Verdict, Autonomy, results). Layer 2 vocabulary.
The contracts are documented in docs/CONTRACTS.md; change both together.
Invariant: Action.summary is regenerated by the gateway, never trusted from the agent.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum, IntEnum
from typing import Any

from pydantic import BaseModel, Field


class Risk(IntEnum):
    SAFE = 1          # read-only: auto-allow, log
    REVERSIBLE = 2    # writes inside the workspace: snapshot first
    EXTERNAL = 3      # effects outside the sandbox: needs approval
    HARD_STOP = 4     # canary touched: freeze the agent


class Verdict(str, Enum):
    ALLOW = "allow"
    ASK = "ask"
    BLOCK = "block"


class Autonomy(str, Enum):
    SUPERVISED = "supervised"    # ask for reversible + external actions
    BALANCED = "balanced"        # ask for external actions (default)
    AUTONOMOUS = "autonomous"    # ask only for critical actions (money, credentials, delete, send)


def new_action_id() -> str:
    return "a" + uuid.uuid4().hex[:8]


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class Action(BaseModel):
    """What the agent wants to do. `summary` is regenerated by the gateway, never trusted."""
    id: str = Field(default_factory=new_action_id)
    type: str
    summary: str = ""
    risk: int = int(Risk.SAFE)
    source: str = "native"  # "native" = our own tools; anything else = an external agent (e.g. claude_code) whose tools we only authorize
    details: dict[str, Any] = Field(default_factory=dict)


class PolicyResult(BaseModel):
    verdict: Verdict
    risk: int
    reason: str = ""
    critical: bool = False


class ToolResult(BaseModel):
    ok: bool = True
    output: str = ""
    screenshot_ref: str | None = None


class ActionResult(BaseModel):
    action_id: str
    status: str  # executed | authorized (external agent: allowed to run its own tool) | denied | blocked | frozen | cancelled | error
    ok: bool
    output: str = ""
    reason: str = ""
